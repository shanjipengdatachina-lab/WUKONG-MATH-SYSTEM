/* ============================================================================
 * 原卷（扫描件）—— **后台批卷接口的模拟**（用户 2026-10-01）
 * ----------------------------------------------------------------------------
 * 用户要的功能：
 *   "这个卷子是从哪来？肯定是需要拍照片上传嘛……这是在后台上，就考试管理上传。
 *    我们现在先不做，因为是在后台。那我们就是默认有这么一张卷子……
 *    你就直接读取用就行，我们就模拟这个功能。"
 *   "这个题错了，然后就框出来……让学生给他一个错因，如果学生认可，就让他点一下；
 *    或者说默认是认可，除非他自己再叠加一些原因。"
 *   "当我点击这道题，我可以加一个按钮，查看原题、查看原卷。"
 *
 * **这一层是"后台"的位**：前台只通过 `WK_EXAM_SCAN.of(examId)` 拿一份
 * `{ title, pages, boxes }`。将来后台做好了，**把这个文件换成 fetch 就行**
 * （`of()` 改成 `return fetch('/api/exam-scan?id=' + examId).then(...)`），
 * 视图与"学生认领"那两层一个字都不用动。
 *
 * 三件事写清楚：
 *   ① **坐标是百分比**（相对照片那张图）—— 与图片像素尺寸无关，换图 / 压缩 / 裁边都不用重算；
 *      后台出的也应该是同一套（原图像素坐标除以宽高即可）。
 *   ② **题号的口径**：`q` = 卷面上的题号（1 起），与「试卷」表里那个"第 N 题"同号。
 *      演示阶段这张照片（五上第一单元）与演示考试（E13）**不是同一份卷子**，
 *      所以框是**按"第 k 道错题 ↔ 第 k 个框"的顺序挂上去的**；
 *      接上后台之后，扫描件与题目本来就是同一份，题号天然相等。
 *   ③ **图会越存越多**（用户："这个图片质量的大小……我们可能会存很多很多张卷子，
 *      所以到时候后台会有个功能，把它压缩"）。演示阶段放的是**原图**
 *      （2843×1280 / 约 300KB 一张），压缩那一步在后台做，前台读图这条路不用改。
 * ========================================================================= */
(function () {
  'use strict';

  var TITLE = '五年级上 · 第一单元综合素养评价（QD 版）';

  var PAGES = [
    { file: 'assets/img/exams/wushang-u1-p1.jpg', label: '正面' },
    { file: 'assets/img/exams/wushang-u1-p2.jpg', label: '反面' }
  ];

  /* 一个框 = 卷面上的一道题。`p` 第几页（0 正面 / 1 反面）；`x/y/w/h` 是**百分比**。
     坐标是照照片一个个量出来的（量的时候在图上叠过 5% 一格的刻度）。 */
  var BOXES = [
    /* ---- 正面 ---- */
    { q: 1,  p: 0, x: 13.5, y: 19.5, w: 33, h: 8.5 },   /* 一、填空 1 */
    { q: 3,  p: 0, x: 13.5, y: 32,   w: 33, h: 9 },     /* 一、填空 2 */
    { q: 5,  p: 0, x: 13.5, y: 43.5, w: 33, h: 5.5 },   /* 一、填空 3 */
    { q: 23, p: 0, x: 13.5, y: 54,   w: 33, h: 8 },     /* 一、填空 5 */
    { q: 29, p: 0, x: 48,   y: 44,   w: 27, h: 5 },     /* 二、选择 2 */
    { q: 30, p: 0, x: 48,   y: 50,   w: 27, h: 4 },     /* 二、选择 3 */
    { q: 31, p: 0, x: 48,   y: 54.5, w: 27, h: 8 },     /* 二、选择 4 */
    { q: 32, p: 0, x: 48,   y: 64.5, w: 27, h: 8 },     /* 二、选择 5 */
    /* ---- 反面 ---- */
    { q: 34, p: 1, x: 13.5, y: 6.5,  w: 11, h: 13 },    /* 2. 用竖式计算 · 第 1 道 */
    { q: 36, p: 1, x: 13.5, y: 18.5, w: 11, h: 15 },    /* 2. 用竖式计算 · 第 4 道 */
    { q: 37, p: 1, x: 13.5, y: 36.5, w: 33, h: 28 },    /* 四、解决问题 1（快乐购物） */
    { q: 38, p: 1, x: 48,   y: 4.5,  w: 27, h: 13 },    /* 四、解决问题 2 */
    { q: 39, p: 1, x: 48,   y: 20,   w: 27, h: 12 },    /* 四、解决问题 3 */
    { q: 45, p: 1, x: 48,   y: 50,   w: 27, h: 15 }     /* 四、解决问题 5 */
  ];

  /* 演示阶段只有这一场考试有原卷（照片是五上第一单元的，临时挂在 E13 上） */
  var SCANS = {
    E13: { title: TITLE, pages: PAGES, boxes: BOXES }
  };

  function of(examId) {
    var s = SCANS[examId];
    if (!s) { return null; }
    return { title: s.title, pages: s.pages, boxes: s.boxes };
  }

  /** 这一场里第 q 题（卷面题号，1 起）在不在原卷上 —— 有框才谈得上"查看原题" */
  function boxOf(examId, q) {
    var s = SCANS[examId];
    if (!s) { return null; }
    for (var i = 0; i < s.boxes.length; i += 1) {
      if (s.boxes[i].q === q) { return s.boxes[i]; }
    }
    return null;
  }

  window.WK_EXAM_SCAN = { of: of, boxOf: boxOf, scans: SCANS };
}());
