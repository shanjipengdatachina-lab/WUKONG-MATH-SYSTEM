/* ==========================================================================
   数字白板 —— 「分析 / 答案」的预置数据
   --------------------------------------------------------------------------
   本版**不接真 AI**（设计 §5）：分步引导语、标准答案、注释全是预置的。
   接入真服务时，只需要把下面的 steps() / answer() 换成一次网络调用，
   界面层（whiteboard.js）完全不动 —— 所以这份数据不会因为换模型而返工。

   两条硬规矩（设计 §2 #3 / #6）：
   1. 「分析」只给"该往哪儿看"，**不许出现答案** —— 给了答案，前面几级台阶就没人走了。
   2. 「答案」分干净与带注释两态：注释解释"为什么这么想、哪里易错"。
   ========================================================================== */
window.WK_ANALYSIS = (function () {
  'use strict';

  /* 通用台阶：与具体题目无关，所以**任何题都有得推**。
     刻意一个数字都不写 —— 一写数字就变成答案了。 */
  var SCAFFOLD = [
    '先只看题目在问什么：要求的到底是哪一个量？把它写进下面的框里。',
    '把题目给出的条件逐条抄下来，一条一行，先不管怎么算。',
    '想一想：这些条件和要求的东西之间，隔着哪一步运算？把那一步写下来。',
    '按你写的那一步算一遍，中间结果留在框里。先别急着对答案。'
  ];

  /* 预置答案：只给演示题库里几道最简单的题，其余走 NO_ANSWER。
     result 是"这道题的答案长什么样"，断言用它守住"分析里不许出现答案"这条规矩。 */
  var PRESET = {
    '7a-01': {
      result: '−4',
      lines: [
        { text: '−7 + 3 = −4', note: '异号相加：先比绝对值。|−7| > |3|，所以结果取负号。' },
        { text: '', note: '再用大的绝对值减小的：7 − 3 = 4，连上负号就是 −4。' }
      ]
    },
    '7a-02': {
      result: '10',
      lines: [
        { text: '6 − (−4) = 6 + 4 = 10', note: '减去一个负数等于加上它的相反数。括号里的负号最容易漏。' },
        { text: '', note: '把减法统一成加法之后再算，符号就不会错。' }
      ]
    },
    '7a-03': {
      result: '10',
      lines: [
        { text: '(−2) × (−5) = 10', note: '同号相乘得正 —— 两个负号约掉了。' },
        { text: '', note: '再把绝对值相乘：2 × 5 = 10。' }
      ]
    },
    '7a-04': {
      result: '−3',
      lines: [
        { text: '(−18) ÷ 6 = −3', note: '异号相除得负。' },
        { text: '', note: '绝对值相除：18 ÷ 6 = 3，再补上负号。' }
      ]
    },
    '7a-13': {
      result: 'x = 2',
      lines: [
        { text: '3x + 5 = 11 → 3x = 6 → x = 2', note: '先把不含 x 的项移到一边：两边同时减 5。' },
        { text: '', note: '再把 x 的系数化 1：两边同时除以 3。' }
      ]
    }
  };

  /* 没预置答案时怎么说 —— 要老实，不要编 */
  var NO_ANSWER = '本版的分析与答案是预置演示数据，这道题还没预置标准答案。接入真服务后，这里会由 AI 给出。';

  /* 台阶：本版对所有题给同一套通用台阶。
     接真服务时这里接收题面文字（data.text），返回该题专属的 1~5 级台阶。 */
  function steps(data) {
    return SCAFFOLD.slice();
  }

  /* 答案：没有预置就返回 null，由界面层给出 NO_ANSWER 的说明 */
  function answer(problemId) {
    return PRESET[problemId] || null;
  }

  return {
    steps: steps,
    answer: answer,
    NO_ANSWER: NO_ANSWER,
    SCAFFOLD: SCAFFOLD,
    PRESET: PRESET
  };
})();
